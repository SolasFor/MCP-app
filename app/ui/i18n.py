class Translator(QObject):
    language_changed = pyqtSignal(str, arguments=["language"])

    def __init__(self, initial: str = LANG_RU) -> None:
        super().__init__()
        self._language = initial if initial in SUPPORTED_LANGUAGES else LANG_RU

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str) -> str:
        normalized = language if language in SUPPORTED_LANGUAGES else LANG_RU
        if normalized == self._language:
            return normalized
        self._language = normalized
        self.language_changed.emit(normalized)
        return normalized

    def t(self, key: str, **kwargs: object) -> str:
        table = _STRINGS.get(self._language, _STRINGS[LANG_RU])
        template = table.get(key) or _STRINGS[LANG_RU].get(key) or key
        if kwargs:
            return template.format(**kwargs)
        return template


i18n = Translator(LANG_RU)


def tr(key: str, **kwargs: object) -> str:
    """Translate `key` using the active global `Translator`."""
    return i18n.t(key, **kwargs)


def keys_for(language: str) -> set[str]:
    """Return all registered translation keys for parity checks."""
    return set(_STRINGS.get(language, {}))
